-- OrchestraWriter schema.
-- Order matters: a table must exist before another table can REFERENCE it.
-- Pipeline: a user uploads an audio_file -> it is transcribed into an orchestral_set
--           -> the set is made of sheets, one per instrument part.

-- ---------- enums ----------

CREATE TYPE instrument_family AS ENUM (
    'strings', 'woodwinds', 'brass', 'percussion', 'keyboard', 'voice', 'other'
);

-- ---------- users ----------
-- Managed by Better Auth (server/auth.ts maps its camelCase names to these columns).
-- Credentials are NOT here: a password lives in accounts.password (provider 'credential'),
-- a Google login in an accounts row with provider 'google'. One user, many login methods.
-- BY DEFAULT (not ALWAYS) because Better Auth may supply ids for some writes.

CREATE TABLE users (
    id             INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT        NOT NULL,
    email          TEXT        NOT NULL UNIQUE,
    email_verified BOOLEAN     NOT NULL DEFAULT FALSE,
    image          TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- instruments ----------
-- Lookup table. Seeded once, rarely changes. Other tables point at it,
-- so deleting a row is blocked (RESTRICT) while anything still uses it.

CREATE TABLE instruments (
    id     INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name   VARCHAR(50)       NOT NULL UNIQUE,
    family instrument_family NOT NULL
);

-- ---------- audio files ----------
-- The user's recordings. Bytes live in S3; s3_key is the object key, not a URL.

CREATE TABLE audio_files (
    id                   INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id              INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name                 VARCHAR(100) NOT NULL,
    s3_key               TEXT         NOT NULL UNIQUE,
    audio_length_seconds INTEGER      NOT NULL CHECK (audio_length_seconds > 0),
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ON audio_files (user_id);

-- Many-to-many: which instruments are heard in a recording.
-- Replaces the INT[] column; Postgres cannot enforce a foreign key through an array.

CREATE TABLE audio_file_instruments (
    audio_file_id INTEGER NOT NULL REFERENCES audio_files(id) ON DELETE CASCADE,
    instrument_id INTEGER NOT NULL REFERENCES instruments(id) ON DELETE RESTRICT,
    PRIMARY KEY (audio_file_id, instrument_id)
);

-- ---------- orchestral sets ----------
-- One transcription of a recording into a full score.
-- audio_file_id is nullable with SET NULL so a finished score survives
-- if the user deletes the original recording.

CREATE TABLE orchestral_sets (
    id            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id       INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    audio_file_id INTEGER      REFERENCES audio_files(id) ON DELETE SET NULL,
    name          VARCHAR(100) NOT NULL,
    is_shared     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ON orchestral_sets (user_id);
CREATE INDEX ON orchestral_sets (audio_file_id);

-- ---------- sheets ----------
-- One instrument's part within a set. A sheet belongs to exactly one set,
-- so the foreign key lives here (the "many" side), not as an array on the set.
-- Owner is reachable through the set, so no user_id column is needed.

CREATE TABLE sheets (
    id            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    set_id        INTEGER      NOT NULL REFERENCES orchestral_sets(id) ON DELETE CASCADE,
    instrument_id INTEGER      NOT NULL REFERENCES instruments(id) ON DELETE RESTRICT,
    name          VARCHAR(100) NOT NULL,
    s3_key        TEXT         NOT NULL UNIQUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ON sheets (set_id);
CREATE INDEX ON sheets (instrument_id);
