-- Better Auth tables (besides users, which is in 001_init.sql).
-- Column names were produced by `npm run auth:schema` from the field map in
-- server/auth.ts, then rewritten in this repo's style. If you change that map,
-- regenerate and compare.

-- One row per signed-in browser. `token` is what the session cookie carries.
CREATE TABLE sessions (
    id         INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token      TEXT        NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    ip_address TEXT,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ON sessions (user_id);

-- One row per login method a user has. provider_id is 'credential' for
-- email+password (hash in `password`) or 'google' (tokens in the *_token columns).
CREATE TABLE accounts (
    id                       INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider_id              TEXT        NOT NULL,
    account_id               TEXT        NOT NULL,
    password                 TEXT,
    access_token             TEXT,
    refresh_token            TEXT,
    id_token                 TEXT,
    access_token_expires_at  TIMESTAMPTZ,
    refresh_token_expires_at TIMESTAMPTZ,
    scope                    TEXT,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (provider_id, account_id)
);

CREATE INDEX ON accounts (user_id);

-- Short-lived codes: email verification, password reset, OAuth state.
CREATE TABLE verifications (
    id         INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier TEXT        NOT NULL,
    value      TEXT        NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ON verifications (identifier);
